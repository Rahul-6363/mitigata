"""
respond.py -- What do I do now? (ChronoPath 2.0, Task 5)

WHY THIS FILE EXISTS
--------------------
An analyst who has read the incident, checked the link evidence and understood
the gaps has one question left, and it is the only one with a deadline:

    "What do I do in the next ten minutes?"

Everything before this point is understanding. This is the part where the
understanding has to become a list of things to type into a firewall, a ticket
and a phone call. A tool that stops at "here is a ranked incident" leaves the
most time-critical translation to the person under the most time pressure.

THE QUESTION THIS ANSWERS THAT THE INCIDENT VIEW CANNOT
-------------------------------------------------------
Is it still happening?

An incident has a start and an end time, and the end time is deeply misleading:
it is the last time this GROUP of detections fired, not the last time the
attacker was seen. If `203.228.177.117` kept hitting the estate for three days
after INC-01's final event, the analyst needs to know that before they decide
how urgent this is -- and the incident record cannot tell them, because those
later events were correlated into something else or filtered as noise.

So every indicator here is looked up across the ENTIRE detections table, not
within the incident. That single widening is what turns a historical report
into a containment decision:

    first seen   -- how far back this indicator goes; often earlier than the
                    incident, which means the incident is not the beginning.
    last seen    -- whether it is over. The most important field here.
    occurrences  -- one login or two thousand; changes the response entirely.

PRECEDING ACCESS: WHAT CAME BEFORE THE FIRST DETECTION
------------------------------------------------------
A successful admin login from the internet raises the obvious question: how did
they get the credential? The answer is often sitting in the data just before
the incident -- a burst of failed logins from the same address. So this module
queries the hours before each incident for activity by its accounts and
addresses and reports what it finds.

When it finds nothing it says so explicitly. "No preceding activity was
recorded for these indicators" is a real finding -- it means the credential was
probably not guessed here, which points at reuse, phishing or an insider, and
it is far more useful than an empty section the analyst reads as "not checked".

WHY ACTIONS ARE TEMPLATES AND WHY THEY SAY "RECOMMENDED"
--------------------------------------------------------
The suggested actions are rule-based: a condition observed in the data selects
a block of advice. They are deliberately NOT generated by the language model,
for two reasons. First, ground rule 6 -- nothing in 2.0 may depend on the Groq
call, and containment advice is the last thing that should disappear when an
API key expires mid-demo. Second, an LLM asked for containment steps will
produce fluent, plausible, occasionally wrong instructions, and these are
instructions someone may execute on production infrastructure.

Every item is labelled RECOMMENDED. Nothing here has been done, nothing here
is automated, and the phrasing never implies otherwise. A tool that blurs
"this is suggested" into "this is handled" is dangerous in exactly the moment
it matters most.
"""

from datetime import timedelta

# How far back to look for activity preceding an incident. Six hours covers the
# usual shape -- credential guessing, then a pause, then the successful login --
# without dragging in a whole day of unrelated background.
PRECEDING_HOURS = 6

# Cap on indicators reported per category, so a noisy incident cannot produce a
# page of addresses that nobody will read or act on.
MAX_INDICATORS = 25


def _ensure_table(con):
    con.execute("""
        CREATE TABLE IF NOT EXISTS cp2_indicators (
            incident_id    VARCHAR,
            indicator_type VARCHAR,
            value          VARCHAR,
            first_seen     VARCHAR,
            last_seen      VARCHAR,
            occurrences    BIGINT,
            note           VARCHAR
        )
    """)


def _lookup(con, column, value):
    """
    First seen, last seen and count for one indicator across ALL detections.

    Deliberately NOT scoped to the incident -- see the module notes. This is
    the query that answers "is it still happening?", and scoping it to the
    incident would make it answer "when did this incident happen?", which the
    analyst already knows.
    """
    try:
        row = con.execute(
            f'SELECT MIN(timestamp), MAX(timestamp), COUNT(*), '
            f'SUM(COALESCE(event_count, 1)) '
            f'FROM suspicious_events WHERE "{column}" = ?', [value]).fetchone()
    except Exception:
        return None
    if not row or row[2] in (None, 0):
        return None
    return {"first_seen": row[0], "last_seen": row[1],
            "detections": int(row[2]), "raw_events": int(row[3] or row[2])}


def _created_and_deleted(events):
    """
    Pull account names the incident shows being created or deleted.

    These are the highest-value indicators in an incident, because an account
    that no longer exists cannot be found by looking at the current config --
    an analyst reviewing the firewall tomorrow sees nothing wrong. The name is
    only recoverable from the log, which makes listing it here the difference
    between a reviewable finding and an invisible one.
    """
    import re
    created, deleted = set(), set()
    for e in events:
        text = f"{e.get('raw_msg') or ''} {e.get('message') or ''}"
        for m in re.finditer(r"\badd\s+system\.admin\s+(\S+)", text, re.I):
            created.add(m.group(1).strip('"'))
        for m in re.finditer(r"\bdelete\s+system\.admin\s+(\S+)", text, re.I):
            deleted.add(m.group(1).strip('"'))
        # Windows / EDR shape, via the engine's own parser.
        try:
            import graph_engine
            name = graph_engine._created_account(e)
            if name:
                created.add(name)
        except Exception:
            pass
    return sorted(created), sorted(deleted)


def indicators(con, incident):
    """
    Build the copyable indicator list for one incident, with estate-wide dates.
    """
    events = incident.get("events") or []
    inc_id = incident.get("id", "INC")
    out = []

    accounts = sorted({str(e["user"]).strip() for e in events
                       if e.get("user") and str(e["user"]).strip()
                       not in ("-", "", "N/A", "unknown", "none", "null")})
    ips = sorted({str(e["src_ip"]).strip() for e in events if e.get("src_ip")})
    created, deleted = _created_and_deleted(events)

    inc_end = incident.get("end_time")

    for value in accounts[:MAX_INDICATORS]:
        seen = _lookup(con, "user", value)
        note = ""
        if seen and inc_end and str(seen["last_seen"]) > str(inc_end):
            # The indicator outlived the incident. This is the single most
            # operationally important thing this module can say.
            note = ("STILL ACTIVE after this incident ended -- last seen "
                    f"{seen['last_seen']}, which is after the incident's last "
                    f"event ({inc_end}).")
        out.append({
            "incident_id": inc_id, "indicator_type": "account",
            "value": value,
            "first_seen": str(seen["first_seen"]) if seen else None,
            "last_seen": str(seen["last_seen"]) if seen else None,
            "occurrences": seen["detections"] if seen else 0,
            "note": note,
        })

    for value in ips[:MAX_INDICATORS]:
        seen = _lookup(con, "src_ip", value)
        note = ""
        if seen and inc_end and str(seen["last_seen"]) > str(inc_end):
            note = ("STILL ACTIVE after this incident ended -- last seen "
                    f"{seen['last_seen']}.")
        out.append({
            "incident_id": inc_id, "indicator_type": "source_ip",
            "value": value,
            "first_seen": str(seen["first_seen"]) if seen else None,
            "last_seen": str(seen["last_seen"]) if seen else None,
            "occurrences": seen["detections"] if seen else 0,
            "note": note,
        })

    for value in created:
        seen = _lookup(con, "user", value)
        out.append({
            "incident_id": inc_id, "indicator_type": "account_created",
            "value": value,
            "first_seen": str(seen["first_seen"]) if seen else None,
            "last_seen": str(seen["last_seen"]) if seen else None,
            "occurrences": seen["detections"] if seen else 0,
            "note": ("Created during this incident. "
                     + ("Also deleted during it, so it will not appear in the "
                        "current configuration -- the only record is this log."
                        if value in deleted else
                        "Check whether it still exists.")),
        })

    for value in deleted:
        if value in created:
            continue
        seen = _lookup(con, "user", value)
        out.append({
            "incident_id": inc_id, "indicator_type": "account_deleted",
            "value": value,
            "first_seen": str(seen["first_seen"]) if seen else None,
            "last_seen": str(seen["last_seen"]) if seen else None,
            "occurrences": seen["detections"] if seen else 0,
            "note": "Deleted during this incident, but not created within it.",
        })

    return out


def preceding_access(con, incident, hours=PRECEDING_HOURS, parse_ts=None):
    """
    What the data shows about these indicators BEFORE the incident started.

    Answers "how did they get in?" where the data can, and says so plainly
    where it cannot -- an explicit negative is a finding, an empty section is
    a question mark.
    """
    from datetime import datetime

    def _ts(v):
        if parse_ts:
            return parse_ts(v)
        return datetime.fromisoformat(str(v).replace("Z", "+00:00")
                                      ).replace(tzinfo=None)

    events = incident.get("events") or []
    if not events or not incident.get("start_time"):
        return {"window": None, "rows": [], "summary": "No start time."}

    try:
        start = _ts(incident["start_time"])
    except (ValueError, TypeError):
        return {"window": None, "rows": [], "summary": "Unparseable start time."}

    window_start = start - timedelta(hours=hours)
    accounts = sorted({str(e["user"]).strip() for e in events
                       if e.get("user") and str(e["user"]).strip()
                       not in ("-", "", "N/A", "unknown")})
    ips = sorted({str(e["src_ip"]).strip() for e in events if e.get("src_ip")})
    if not accounts and not ips:
        return {"window": None, "rows": [],
                "summary": "No accounts or addresses to look up."}

    clauses, params = [], []
    if accounts:
        clauses.append(f'"user" IN ({",".join("?" for _ in accounts)})')
        params.extend(accounts)
    if ips:
        clauses.append(f'src_ip IN ({",".join("?" for _ in ips)})')
        params.extend(ips)

    try:
        rows = con.execute(f"""
            SELECT timestamp, "user", src_ip, rule_name, mitre_technique,
                   status, outcome, COALESCE(event_count, 1) AS raw
            FROM suspicious_events
            WHERE timestamp >= ? AND timestamp < ?
              AND ({" OR ".join(clauses)})
            ORDER BY timestamp
            LIMIT 200
        """, [str(window_start).replace(" ", "T"),
              str(start).replace(" ", "T")] + params).fetchall()
        cols = [d[0] for d in con.description]
    except Exception:
        return {"window": (window_start, start), "rows": [],
                "summary": "Could not query preceding activity."}

    found = [dict(zip(cols, r)) for r in rows]

    if not found:
        summary = (
            f"No activity was recorded for these indicators in the {hours} "
            f"hours before the first detection ({window_start} to {start}). "
            f"That is a finding, not a blank: there is no credential-guessing "
            f"burst here to explain the access, so the credential was most "
            f"likely obtained elsewhere -- reuse, phishing, or a legitimate "
            f"holder. The absence of a brute-force run is itself evidence "
            f"about how this started."
        )
    else:
        failed = sum(int(r["raw"]) for r in found
                     if r.get("outcome") in ("attempted", "prevented"))
        succeeded = sum(int(r["raw"]) for r in found
                        if r.get("outcome") == "observed")
        bits = [f"{len(found)} detection(s) covering {failed + succeeded:,} "
                f"raw events"]
        if failed:
            bits.append(f"{failed:,} attempted or blocked")
        if succeeded:
            bits.append(f"{succeeded:,} allowed")
        summary = (
            f"In the {hours} hours before the first detection "
            f"({window_start} to {start}): {', '.join(bits)}. "
            f"Review these for the origin of the access."
        )

    return {"window": (window_start, start), "rows": found,
            "summary": summary}


def suggested_actions(incident, gap_rows=None):
    """
    Containment steps selected by conditions observed in the data.

    Each returned item carries the OBSERVATION that triggered it, so the
    analyst can see why they are being told to do something and overrule it.
    Advice without its trigger is just a checklist, and checklists get followed
    in situations they were never meant for.
    """
    import re

    events = incident.get("events") or []
    techniques = {str(e.get("mitre_technique") or "") for e in events}
    text = " ".join(f"{e.get('raw_msg') or ''} {e.get('rule_name') or ''}"
                    for e in events).lower()
    created, deleted = _created_and_deleted(events)
    ips = sorted({str(e["src_ip"]).strip() for e in events if e.get("src_ip")})
    accounts = sorted({str(e["user"]).strip() for e in events
                       if e.get("user") and str(e["user"]).strip()
                       not in ("-", "", "N/A", "unknown")})

    actions = []

    def add(observation, steps, priority):
        actions.append({"observation": observation, "steps": steps,
                        "priority": priority, "status": "RECOMMENDED"})

    # Account created then deleted -- the strongest signal in this data set,
    # because the evidence erases itself from the live configuration.
    both = sorted(set(created) & set(deleted))
    if both:
        add(f"The administrative account(s) {', '.join(both)} were created and "
            f"deleted inside this incident.",
            [f"Audit every configuration change made by {', '.join(both)} "
             f"between its creation and deletion -- the account is gone, so "
             f"the current config will look clean.",
             "Check specifically for persistence that outlives the account: "
             "new VPN users, added firewall policies, port forwards, "
             "additional admin accounts, modified trusted hosts.",
             "Compare the running configuration against the last known-good "
             "backup, rather than reviewing it on its own.",
             "Preserve the configuration revision history before it rotates."],
            "immediate")
    elif created:
        add(f"The administrative account(s) {', '.join(created)} were created "
            f"during this incident.",
            [f"Confirm whether {', '.join(created)} still exists and whether "
             f"it was authorised by a change record.",
             "If unauthorised, disable rather than delete -- deleting destroys "
             "the evidence of what it was used for.",
             "Review everything it did since creation."],
            "immediate")

    # Administrative access from the internet.
    if {"T1078", "T1078.003"} & techniques or "login successful from external" in text:
        who = ", ".join(accounts[:4]) or "the affected accounts"
        add(f"Administrative authentication succeeded from an external address "
            f"for {who}.",
            [f"Reset credentials for {who} and terminate active sessions.",
             "Restrict the administrative interface to a management network "
             "or VPN -- an admin interface reachable from the internet is the "
             "precondition for this whole incident.",
             "Require MFA for administrative access if it is not enforced.",
             "Check whether the same credentials succeeded on other systems."],
            "immediate")

    # Logging or policy interference.
    if any(t.startswith("T1562") for t in techniques) or "logging disabled" in text:
        add("A defensive control was interfered with (logging disabled and/or "
            "policy objects purged).",
            ["Re-enable logging and confirm it is forwarding off-box, so the "
             "next attempt cannot blind the local copy.",
             "Diff the current configuration against the last backup to "
             "establish exactly what the purge removed.",
             "Retrieve the FortiAnalyzer or remote syslog copy for the window "
             "to corroborate what the on-box log holds.",
             "Restore any firewall policies that were removed."],
            "immediate")

    # VPN access from two countries -- impossible travel.
    if "T1133" in techniques or "multiple countries" in text:
        who = ", ".join(accounts[:3]) or "the affected account"
        add(f"VPN access for {who} was seen from more than one country within "
            f"a short interval.",
            [f"Reset credentials for {who} and revoke active VPN sessions.",
             "Review the MFA configuration for VPN access; impossible travel "
             "usually means a shared or stolen credential.",
             "Check whether the same account was used for any administrative "
             "action during the overlap."],
            "high")

    # Anti-forensic indicator removal.
    if "T1070" in techniques:
        add("Activity consistent with indicator removal was observed.",
            ["Preserve the current logs and configuration revisions now, "
             "before anything rotates.",
             "Treat the absence of later evidence as unresolved rather than "
             "as proof that activity stopped."],
            "high")

    # Always, last: block the addresses. Phrased with the caveat that matters,
    # because blocking a shared NAT address can cut off legitimate users.
    if ips:
        add(f"External address(es) involved: {', '.join(ips[:6])}"
            + ("..." if len(ips) > 6 else ""),
            [f"Block {', '.join(ips[:6])} at the perimeter if they are not "
             f"known-good. Confirm first that none is a shared NAT, VPN exit "
             f"or partner address that legitimate users depend on.",
             "Add them to a watchlist regardless of whether you block them, "
             "so a return is noticed."],
            "standard")

    # Surface the gaps as explicit requests. An analyst's output is often a
    # request to another team, and this is where it belongs.
    if gap_rows:
        requests = [g["evidence_request"] for g in gap_rows
                    if g.get("evidence_request")]
        if requests:
            add("Evidence needed to answer what this data cannot "
                f"({len(requests)} open gap(s) for this incident).",
                requests, "follow-up")

    return actions


def analyse(con, incidents, gaps_by_incident=None, persist=True, parse_ts=None):
    """
    Build the respond-now panel for every incident.

    Returns {incident_id: {...}}. The indicator table is persisted because the
    dashboard and API read it; preceding access and actions are derived on
    demand, being cheap and dependent on the gap ledger.
    """
    _ensure_table(con)
    gaps_by_incident = gaps_by_incident or {}
    out, rows = {}, []

    for inc in incidents:
        inc_id = inc.get("id", "INC")
        ind = indicators(con, inc)
        rows.extend(ind)
        out[inc_id] = {
            "indicators": ind,
            "preceding": preceding_access(con, inc, parse_ts=parse_ts),
            "actions": suggested_actions(inc, gaps_by_incident.get(inc_id)),
        }

    if persist:
        con.execute("DELETE FROM cp2_indicators")
        if rows:
            con.executemany(
                "INSERT INTO cp2_indicators VALUES (?,?,?,?,?,?,?)",
                [(r["incident_id"], r["indicator_type"], r["value"],
                  r["first_seen"], r["last_seen"], r["occurrences"], r["note"])
                 for r in rows])
    return out


def get_indicators(con, incident_id=None):
    """Read the indicator table back for the dashboard and API."""
    try:
        if incident_id:
            rows = con.execute(
                "SELECT * FROM cp2_indicators WHERE incident_id = ? "
                "ORDER BY indicator_type, value", [incident_id]).fetchall()
        else:
            rows = con.execute(
                "SELECT * FROM cp2_indicators ORDER BY incident_id, "
                "indicator_type, value").fetchall()
        cols = [d[0] for d in con.description]
    except Exception:
        return []
    return [dict(zip(cols, r)) for r in rows]
